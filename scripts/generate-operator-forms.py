"""Generate consumed-argument metadata from the native operator tables.

Run after editing Jl* operation lambdas. Helpers receiving the argument bundle
are followed, and region structuring-element Size is included explicitly.
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sources = {
    'imageOp': 'JlImageOperations', 'regionOp': 'JlRegionOperations',
    'regionFeature': 'JlRegionFeatures', 'geometry': 'JlGeometryOperations',
    'matrixOp': 'JlMatrixOperations', 'homMat': 'JlHomMatOperations',
    'contourOp': 'JlContourOperations', 'threshold': 'JlThresholdOperations',
    'contourFeature': 'JlContourFeatures',
}

def consumed(body, source, visited=None):
    visited = set() if visited is None else visited
    fields = set(re.findall(r'\ba\.(\w+)', body))
    for name in re.findall(r'\b(\w+)\(a(?:\s*[,)]|\s*\))', body):
        if name in visited:
            continue
        visited.add(name)
        match = re.search(r'private static[^\n]+\b' + name + r'\([^{}]*\b\w+Args a\b[^{}]*\)\s*\{(.*?)^    \}', source, re.M | re.S)
        if not match:
            raise ValueError('Argument helper needs metadata support: ' + name)
        fields.update(consumed(match.group(1), source, visited))
    return fields

lines = ['// Generated by scripts/generate-operator-forms.py. Do not edit.',
         'namespace VisionStudio.Engine;', '', 'internal static class OperatorParameterUsage', '{',
         '    internal static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, string[]>> ByNode =',
         '        new Dictionary<string, IReadOnlyDictionary<string, string[]>>(StringComparer.Ordinal)', '        {']
for node, filename in sources.items():
    source = (root / 'backend/src/VisionStudio.Engine/Algorithms' / (filename + '.cs')).read_text(encoding='utf-8')
    entries = list(re.finditer(r'^        \["([^"]+)"\] = new\(', source, re.M))
    table_end = source.index('\n    };', entries[-1].end())
    lines += ['            ["jlvision.' + node + '"] = new Dictionary<string, string[]>(StringComparer.Ordinal)', '            {']
    for i, entry in enumerate(entries):
        body = source[entry.end():entries[i + 1].start() if i + 1 < len(entries) else table_end]
        fields = consumed(body, source)
        if node in ('regionOp', 'imageOp') and 'NeedsStructuringElement: true' in body:
            fields.add('Size')
        args = sorted({'A': 'matrixA', 'B': 'matrixB'}.get(f, f[0].lower() + f[1:]) for f in fields)
        lines.append('                [' + json.dumps(entry.group(1)) + '] = [' + ', '.join(json.dumps(arg) for arg in args) + '],')
    lines += ['            },']
lines += ['        };', '}', '']
(root / 'backend/src/VisionStudio.Engine/OperatorParameterUsage.generated.cs').write_text('\n'.join(lines), encoding='utf-8')

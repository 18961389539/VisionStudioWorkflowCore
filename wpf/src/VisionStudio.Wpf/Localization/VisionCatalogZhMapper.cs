    public static string TranslateCategory(string category)
        => CategoryMap.TryGetValue(category, out var zh) ? zh : category;

    public static string TranslateNodeName(NodeCatalogItem item)
        => NodeNameMap.TryGetValue(item.Type, out var zh) ? zh : item.DisplayName;

    public static string TranslateNodeName(string nodeType, string? fallback = null)
        => NodeNameMap.TryGetValue(nodeType, out var zh) ? zh : (string.IsNullOrWhiteSpace(fallback) ? nodeType : fallback);

